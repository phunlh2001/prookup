// Shared domain model for Prookup — used by both the research API (server/)
// and the dashboard (src/). Keep this file free of runtime dependencies.

export type TrendDirection = 'rising' | 'stable' | 'declining'

export type OpportunityLevel = 'excellent' | 'promising' | 'moderate' | 'low'

export type ConfidenceLevel = 'high' | 'medium' | 'low'

/** Where a piece of data came from. Every external datum carries one. */
export interface DataSource {
  /** Provider id, e.g. "serpapi-google-trends" or "mock-trends". */
  provider: string
  /** Human label shown in the UI, e.g. "Google Trends (via SerpApi)". */
  label: string
  kind: 'trends' | 'search' | 'supplier'
  /** ISO timestamp of when this data was fetched from the provider. */
  fetchedAt: string
  /** True when the value was generated by a demo provider, not collected. */
  simulated: boolean
  url?: string
}

export interface InterestPoint {
  /** ISO date (week start). */
  date: string
  /** Google Trends relative interest, 0–100. */
  value: number
}

export interface RegionInterest {
  /** US state name. */
  region: string
  code: string
  value: number
}

export interface RelatedQuery {
  query: string
  /** Growth label from Google Trends, e.g. "+250%" or "Breakout". */
  growth: string
}

export interface TrendSignal {
  /** Average relative interest over the last 4 weeks (0–100). */
  interestScore: number
  /** Last 3 months vs the 3 months before, in percent. */
  growthPct: number
  direction: TrendDirection
  /** Least-squares slope of the last 12 weeks, normalised to −100…100. */
  momentum: number
  series: InterestPoint[]
  regions: RegionInterest[]
  relatedQueries: RelatedQuery[]
  source: DataSource
}

export interface SupplierOffer {
  supplierName: string
  /** Unit cost in USD. */
  sourcingCost: number
  /** Estimated shipping cost to the US in USD, if the supplier reports one. */
  shippingCost: number | null
  availability: 'in_stock' | 'limited' | 'unknown'
  shippingDays: string | null
  url?: string
  source: DataSource
}

export interface CompetitionSignal {
  level: 'low' | 'medium' | 'high'
  /** 0 (no competition) – 100 (saturated). */
  index: number
  /** Raw evidence, e.g. number of shopping listings / ads seen. */
  evidence: string
  source: DataSource
}

export interface Niche {
  id: string
  name: string
  /** Google Trends search keyword used for this niche. */
  keyword: string
  icon: string
  trend: TrendSignal
  productCount: number
  researchedAt: string
}

export interface Product {
  id: string
  name: string
  nicheId: string
  keyword: string
  description: string
  characteristics: string[]
  images: string[]
  discoveredAt: string
  trend: TrendSignal
  supplier: SupplierOffer | null
  competition: CompetitionSignal | null
  /** Pricing computed with the server-side default assumptions. */
  pricing: PricingResult | null
  score: OpportunityScore
}

// ---------- Pricing ----------

export interface PricingAssumptions {
  /** Used when the supplier does not report shipping, USD per unit. */
  defaultShippingCost: number
  /** Payment processor percentage fee, e.g. 0.029 = 2.9 %. */
  paymentFeePct: number
  /** Payment processor fixed fee per order in USD. */
  paymentFeeFixed: number
  /** Advertising cost per acquired order (CPA) in USD. */
  adCostPerOrder: number
  /** Net margin the recommended price should leave after modeled costs. */
  targetNetMargin: number
  /** Floor: selling price must be at least this multiple of landed cost. */
  minLandedMultiple: number
  /** Round prices up to a .99 ending. */
  charmPricing: boolean
}

export interface PricingResult {
  sourcingCost: number
  shippingCost: number
  shippingEstimated: boolean
  landedCost: number
  paymentFees: number
  adCost: number
  recommendedPrice: number
  /** Price − landed cost (sourcing + shipping). */
  grossProfit: number
  grossMargin: number
  /** Gross profit − payment fees − ad cost. */
  netProfit: number
  netMargin: number
  /** Which rule set the price ("target-margin" or "landed-multiple"). */
  priceDriver: 'target-margin' | 'landed-multiple'
  assumptions: PricingAssumptions
}

// ---------- Scoring ----------

export type ScoreFactorKey =
  | 'momentum'
  | 'demand'
  | 'growth'
  | 'grossProfit'
  | 'margin'
  | 'competition'
  | 'confidence'

export interface ScoreFactor {
  key: ScoreFactorKey
  label: string
  /** Normalised factor value 0–100. */
  value: number
  /** Effective weight after redistributing missing factors (sums to 1). */
  weight: number
  available: boolean
}

export interface OpportunityScore {
  total: number
  level: OpportunityLevel
  confidence: ConfidenceLevel
  factors: ScoreFactor[]
}

// ---------- API payloads ----------

export type SyncState = 'idle' | 'syncing' | 'success' | 'error'

export interface ProviderStatus {
  kind: DataSource['kind']
  provider: string
  label: string
  simulated: boolean
  configured: boolean
}

export interface SyncStatus {
  state: SyncState
  lastSuccessAt: string | null
  lastAttemptAt: string | null
  nextScheduledAt: string | null
  lastError: string | null
  /** True if every provider in use is a demo provider. */
  simulated: boolean
  providers: ProviderStatus[]
  manualCooldownUntil: string | null
}

export interface OverviewStat {
  current: number
  previous: number | null
  /** Small history for sparklines (oldest → newest). */
  history: number[]
}

export interface MarketOverview {
  trendingNiches: OverviewStat
  trendingProducts: OverviewStat
  risingProducts: OverviewStat
  opportunities: OverviewStat
}

export interface ResearchSnapshot {
  market: 'US'
  generatedAt: string
  niches: Niche[]
  products: Product[]
  overview: MarketOverview
  /** Top product ids ranked by opportunity score (computed, never hardcoded). */
  recommendedIds: string[]
}
